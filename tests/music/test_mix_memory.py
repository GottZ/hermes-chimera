"""K-5.10 test_mix_memory (TESTPLAN L5, P1-05): mixing 8 voices × 300 s (FakeVoice) raises the peak RSS of the host
process by at most 64 MB, and the temporary files are gone afterwards - also after an abort. Red proof: collect the
voices as a float64 list in memory (8 × 300 s × 48 000 × 8 B = 922 MB).

The mixer runs in a fresh subprocess (ru_maxrss of RUSAGE_SELF: worker/generator children are not counted). The
voice files are generated by FakeVoice in separate processes first (two distinct voices, copied to eight files)."""

from __future__ import annotations

import json
import os
import shutil
import subprocess
import sys
import textwrap
from pathlib import Path

import pytest

from support import REPO_ROOT, TESTS_DIR

resource = pytest.importorskip("resource", reason="ru_maxrss needs the POSIX resource module")

LIMIT_MB = 64.0
SECONDS = 300
N = SECONDS * 48000

GEN = textwrap.dedent(r"""
    import sys
    sys.path[:0] = [sys.argv[1], sys.argv[2]]
    import numpy as np
    from support.fakes import FakeVoice
    from chimera_vocal.core.types import Gesture, Seeds
    out, n, f0, seed = sys.argv[3], int(sys.argv[4]), float(sys.argv[5]), int(sys.argv[6])
    v = FakeVoice(seeds=Seeds.for_voice(seed))
    v.set_source({"f0": f0})
    v.settle_pitch()
    v.schedule([Gesture(0.05, n / 48000.0 - 0.2, 0.04, 0.1, 1.0, {"breath": 1.0}, label="breath")])
    with open(out, "wb") as f:
        done = 0
        while done < n:
            k = min(1 << 18, n - done)
            f.write(v.render(k).astype("<f4").tobytes())
            done += k
""")

MIX = textwrap.dedent(r"""
    import json, os, resource, sys
    sys.path[:0] = [sys.argv[1], sys.argv[2]]
    import numpy as np
    from chimera_vocal.music.mixer import MixWriter
    from chimera_vocal.music.compile import VoiceMix
    tmp, wav, n, abort_after = sys.argv[3], sys.argv[4], int(sys.argv[5]), int(sys.argv[6])
    files = json.loads(sys.argv[7])
    scale = 1024.0 if sys.platform != "darwin" else 1024.0 * 1024.0
    base = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss / scale
    w = MixWriter(tmp, n, stereo=True)
    info = None
    pans = [-1.0, -0.6, -0.3, 0.0, 0.0, 0.3, 0.6, 1.0]
    try:
        for i, p in enumerate(files):
            if i == abort_after:
                w.abort()
                break
            w.add_voice(p, n, VoiceMix(offset=0, gain_db=-6.0, pan=pans[i], gain_env=None))
        else:
            info = w.finish(wav)
    except BaseException:
        w.abort()
        raise
    peak = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss / scale
    print(json.dumps({"base_mb": base, "peak_mb": peak, "info": None if info is None else info.__dict__}))
""")


def _run(code: str, *args: str, timeout: float = 600) -> str:
    r = subprocess.run([sys.executable, "-c", code, str(REPO_ROOT), str(TESTS_DIR), *args],
                       capture_output=True, text=True, timeout=timeout)
    assert r.returncode == 0, r.stderr[-4000:]
    return r.stdout


@pytest.fixture(scope="module")
def voice_files(tmp_path_factory):
    d = tmp_path_factory.mktemp("voices")
    srcs = [str(d / "src-a.f32"), str(d / "src-b.f32")]
    procs = [subprocess.Popen([sys.executable, "-c", GEN, str(REPO_ROOT), str(TESTS_DIR), p, str(N), f0, s])
             for p, f0, s in ((srcs[0], "220.0", "1"), (srcs[1], "147.0", "2"))]
    for p in procs:
        assert p.wait(timeout=600) == 0
    files = []
    for i in range(8):
        f = d / f"voice-{i}.f32"
        shutil.copyfile(srcs[i % 2], f)
        files.append(str(f))
    return d, files


def _fresh_copies(src_files: list[str], into: Path) -> list[str]:
    into.mkdir(parents=True, exist_ok=True)
    out = []
    for i, f in enumerate(src_files):
        dst = into / f"voice-{i}.f32"
        shutil.copyfile(f, dst)
        out.append(str(dst))
    return out


def test_mix_memory(voice_files, tmp_path):
    _, files = voice_files
    tmp = tmp_path / "mixtmp"
    copies = _fresh_copies(files, tmp)
    wav = tmp_path / "mix.wav"
    out = json.loads(_run(MIX, str(tmp), str(wav), str(N), "-1", json.dumps(copies)).splitlines()[-1])
    grown = out["peak_mb"] - out["base_mb"]
    assert grown <= LIMIT_MB, f"host peak RSS grew by {grown:.1f} MB (> {LIMIT_MB} MB) mixing 8 × {SECONDS} s"
    assert wav.stat().st_size == 44 + N * 2 * 2, "16-bit stereo WAV of the full mix length"
    left = [p for p in tmp.rglob("*") if p.is_file()] if tmp.exists() else []
    assert left == [], f"temporary files left: {left}"
    assert out["info"]["channels"] == 2 and out["info"]["clipped_samples"] == 0


def test_mix_abort_cleans_up(voice_files, tmp_path):
    _, files = voice_files
    tmp = tmp_path / "mixtmp"
    copies = _fresh_copies(files[:4], tmp)
    wav = tmp_path / "mix.wav"
    _run(MIX, str(tmp), str(wav), str(N), "2", json.dumps(copies))
    owned = [p for p in tmp.rglob("*") if p.is_file() and p.name not in {Path(c).name for c in copies[2:]}] \
        if tmp.exists() else []
    assert owned == [], f"files left after abort: {owned}"
    assert not wav.exists() or wav.stat().st_size == 0


E2E = textwrap.dedent(r"""
    import json, os, resource, sys, threading
    sys.path[:0] = [sys.argv[1], sys.argv[2]]
    os.environ["CHIMERA_WORKER_VOICE_FACTORY"] = "support.fakes:fake_voice_factory"
    import numpy as np
    from support.fakes import STUB_DICTIONARY, StubG2P, StubPlanner
    from chimera_vocal.music.planning import set_planner_api
    import chimera_vocal.scheduler as sched
    sched._numba_installed = lambda: False
    sched._marker_ok = lambda base: None
    from chimera_vocal import Engine, EngineConfig, RenderCancelled
    set_planner_api(StubPlanner(StubG2P(STUB_DICTIONARY)).api())
    out_dir, cancel_at, seconds = sys.argv[3], float(sys.argv[4]), float(sys.argv[5])
    eng = Engine(EngineConfig(workers=4, cache_dir=os.path.join(out_dir, "..", "cache")))
    beats = int(seconds) - 1
    notes = [{"pitch": 60 + (k % 5), "beats": 1, "lyric": "ah"} for k in range(beats)]
    score = {"bpm": 60, "voices": [{"body": "female", "pan": -1 + 2 * i / 7, "notes": notes} for i in range(8)]}
    scale = 1024.0 if sys.platform != "darwin" else 1024.0 * 1024.0
    eng.check_score(score)
    base = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss / scale
    cancel = threading.Event()
    def progress(p):
        if cancel_at >= 0 and p >= cancel_at:
            cancel.set()
    res = {"cancelled": False}
    try:
        r = eng.render_score(score, out_dir, "mem", want_mp3=False, progress=progress, cancel=cancel)
        res["wav"] = r.path_wav
    except RenderCancelled:
        res["cancelled"] = True
    res["peak_mb"] = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss / scale
    res["base_mb"] = base
    eng.shutdown()
    print(json.dumps(res))
""")


def test_engine_render_memory_and_cleanup(tmp_path):
    out_dir = tmp_path / "out"
    out_dir.mkdir()
    res = json.loads(_run(E2E, str(out_dir), "-1", "60").splitlines()[-1])
    grown = res["peak_mb"] - res["base_mb"]
    assert grown <= LIMIT_MB, f"host peak RSS grew by {grown:.1f} MB rendering 8 voices × 60 s"
    assert sorted(p.name for p in out_dir.iterdir()) == [Path(res["wav"]).name], "only the WAV remains"


def test_engine_cancel_cleanup(tmp_path):
    out_dir = tmp_path / "out"
    out_dir.mkdir()
    res = json.loads(_run(E2E, str(out_dir), "0.2", "60").splitlines()[-1])
    assert res["cancelled"] is True
    assert list(out_dir.iterdir()) == [], f"left after cancel: {list(out_dir.iterdir())}"
